using System.Globalization;
using System.Text;
using Nomenclador.Web.Data.Seed;

namespace Nomenclador.Web.Herramientas;

/// <summary>Genera el archivo NomencladorSeed.cs con todos los datos del nomenclador.</summary>
public static class SeedWriter
{
    public static string Generar(IEnumerable<SeccionSeed> secciones, IEnumerable<GrupoSeed> grupos, IEnumerable<PracticaSeed> practicas, string origen)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"// Generado {DateTime.Now:yyyy-MM-dd HH:mm} desde {origen}.");
        sb.AppendLine("// Para regenerarlo: dotnet run -- generar-seed   (lee data/raw/*.txt)");
        sb.AppendLine("// o desde Admin > Exportar (toma la base de datos actual).");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("namespace Nomenclador.Web.Data.Seed;");
        sb.AppendLine();
        sb.AppendLine("public static class NomencladorSeed");
        sb.AppendLine("{");

        sb.AppendLine("    public static readonly SeccionSeed[] Secciones =");
        sb.AppendLine("    [");
        foreach (var s in secciones)
            sb.AppendLine($"        new({Str(s.Codigo)}, {Str(s.Nombre)}),");
        sb.AppendLine("    ];");
        sb.AppendLine();

        sb.AppendLine("    public static readonly GrupoSeed[] Grupos =");
        sb.AppendLine("    [");
        foreach (var g in grupos)
            sb.AppendLine($"        new({Str(g.Codigo)}, {Str(g.SeccionCodigo)}, {Str(g.Nombre)}, {StrN(g.Nota)}),");
        sb.AppendLine("    ];");
        sb.AppendLine();

        sb.AppendLine("    public static readonly PracticaSeed[] Practicas =");
        sb.AppendLine("    [");
        foreach (var p in practicas)
            sb.AppendLine($"        new({Str(p.Codigo)}, {Str(p.Estado)}, {Str(p.Descripcion)}, {Dec(p.UEspecialista)}, {Int(p.AyudantesCantidad)}, {Dec(p.UAyudante)}, {Dec(p.UAnestesista)}, {Dec(p.UGasto)}, {StrN(p.CoefGasto)}, {StrN(p.Nota)}),");
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string Str(string s) => SymbolDisplay(s);
    private static string StrN(string? s) => s is null ? "null" : SymbolDisplay(s);
    private static string Dec(decimal? d) => d is null ? "null" : d.Value.ToString(CultureInfo.InvariantCulture) + "m";
    private static string Int(int? i) => i is null ? "null" : i.Value.ToString(CultureInfo.InvariantCulture);

    private static string SymbolDisplay(string s)
    {
        var sb = new StringBuilder(s.Length + 2);
        sb.Append('"');
        foreach (var c in s)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': break;
                case '\t': sb.Append("\\t"); break;
                default: sb.Append(c); break;
            }
        }
        sb.Append('"');
        return sb.ToString();
    }
}
